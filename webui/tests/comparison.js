const assert = require('assert');
const {toggle, compact, eligible, keyOf, label, remember} = require('../lib/comparison');
const row = i => ({supi:'imsi-'+i,seid:String(i),psi:1,trend_key:'session:'+i,ul_bps:'100'});
let rows=[];for(let i=0;i<8;i++)rows=toggle(rows,row(i),'session');
assert.strictEqual(rows.length,8);assert.strictEqual(new Set(rows.map(r=>r.color)).size,8);
assert.throws(()=>toggle(rows,row(8),'session'),/最多选择/);
const colors=rows.map(r=>r.color);rows=toggle(rows,row(3),'session');rows=toggle(rows,row(8),'session');
assert.strictEqual(rows[7].color,colors[3]);assert.strictEqual(rows[0].color,colors[0]);
assert.strictEqual(keyOf({seid:'1',pdr_id:2},'rule'),'rule:1:2');
assert(eligible({pdr_id:1,rule_kind:'business',qfi:0},'rule'));assert(!eligible({pdr_id:1,rule_kind:'internal'},'rule'));
assert(!eligible({pdr_id:1,rule_kind:'unknown'},'rule'));assert(!eligible({rule_kind:'business'},'rule'));
assert(!('rules' in compact({...row(1),rules:new Array(10000)},'session')));
assert(label({supi:'imsi-123456789012345',seid:'1',psi:1},'session',true).includes('imsi-123456789012345'));
const cache=new Map();for(let i=0;i<100;i++)remember(cache,String(i),{data:{points:[[i,1,2]]}});
assert.strictEqual(cache.size,16);assert(!cache.has('0'));
for(let i=0;i<20;i++)remember(cache,'large'+i,{data:{points:new Array(20000).fill([1,2,3])}});
assert([...cache.values()].reduce((n,v)=>n+v.bytes,0)<=8*1024*1024);
assert.throws(()=>remember(cache,'oversized',{data:{text:'x'.repeat(3*1024*1024)}}));
console.log('Comparison identity, eligibility, 8-object selection, stable colors, bounded metadata and cache: OK');
